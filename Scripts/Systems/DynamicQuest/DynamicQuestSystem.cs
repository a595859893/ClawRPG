    // Active quests
    private List<Quest> _availableQuests = new();
    private List<Quest> _activeQuests = new();
    private List<Quest> _completedQuests = new();
    private List<Quest> _failedQuests = new();
    private Random _rng = new();
    private int _questCounter = 0;
    
    // Signals
    public delegate void QuestGeneratedEventHandler(Quest quest);
